class _IndentedDumper(yaml.SafeDumper):
    """Keep sequence entries visibly nested under their mapping key."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _deep_merge(base: Mapping, override: Mapping) -> dict:
    """Return a recursive merge where explicit scenario values win."""
    result = dict(base)
    for key, value in override.items():
        if isinstance(value, Mapping) and isinstance(result.get(key), Mapping):
            result[key] = _deep_merge(result[key], value)
        else:
            result[key] = value
    return result


def scenario_settings(
    template: Mapping, path: Path, workbook: Path, root: Path, *, merge: bool = False,
) -> dict:
    """Resolve the settings both members of a generated pair must share.

    On merge, active values in the existing scenario YAML override template
    defaults. The workbook is then rebuilt from those resolved settings, so
    workbook sheets and scenario years cannot diverge from their companion
    config. The destination name and workbook basename remain generator-owned.
    """
    base_path = root / "base_config.yaml"
    base = yaml.safe_load(base_path.read_text(encoding="utf-8")) or {}
    selected = {key: value for key, value in template.items() if key != "template"}
    effective = _deep_merge(base, selected)
    # These are workflow controls or derived locations, never scenario inputs.
    effective.pop("run", None)
    if path.exists() and merge:
        current = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        if not isinstance(current, Mapping):
            raise ValueError(f"{path} must contain a YAML mapping to merge it safely.")
        effective = _deep_merge(effective, current)
    effective.pop("run", None)
    effective.setdefault("scenario", {})["name"] = str(template["scenario"]["name"])
    paths = dict(effective.get("paths", {}) or {})
    paths.pop("scenario_dir", None)
    paths["workbook"] = workbook.name
    effective["paths"] = paths
    return effective


def scenario_text(settings: Mapping) -> str:
    """A readable config with a usable constraints list and optional examples."""
    header = (
        "# Scenario-local settings generated by `snakemake generate_template`.\n"
        "# Edit active values for this scenario; repeat generation with\n"
        "# template.merge: true preserves those edits.\n"
        "# Template-only controls are kept in generate_template.yaml.\n\n"
    )
    active = dict(settings)
    # Keep this parent directly before the catalogue. With no policies it is a
    # valid null; removing '# ' from an example then turns it into this list.
    constraints = active.pop("constraints", None)
    active["constraints"] = constraints
    dumped = yaml.dump(
        active, Dumper=_IndentedDumper, sort_keys=False, allow_unicode=True,
    )
    if constraints is None or constraints == []:
        # An empty mapping value accepts a subsequently uncommented nested list;
        # explicit ``null``/``[]`` scalars emitted by PyYAML do not.
        dumped = dumped.replace("constraints: null\n", "constraints:\n", 1)
        dumped = dumped.replace("constraints: []\n", "constraints:\n", 1)
    return header + dumped + "\n" + catalogue() + "\n"


def write_scenario_config(
    template: Mapping, path: Path, *, workbook: Path, root: Path = ROOT,
    merge: bool = False, force: bool = False, check_only: bool = False,
    settings: Mapping | None = None,
) -> str:
    """Write one config beside its workbook, protecting an existing pair.

    Merge overlays an existing scenario YAML on the newly generated effective
    settings, so user values win while fresh defaults and the catalogue remain.
    Force saves the existing YAML as ``.bak`` before replacement.
    """
    if path.exists() and not (merge or force):
        raise ValueError(
            f"{path} already exists and has been preserved; enable template.merge "
            "or template.force to regenerate the scenario pair."
        )
    settings = dict(settings) if settings is not None else scenario_settings(
        template, path, workbook, root, merge=merge
    )
    if check_only:
        return "checked"
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and force:
        backup = path.with_suffix(path.suffix + ".bak")
        backup.write_bytes(path.read_bytes())
    path.write_text(scenario_text(settings), encoding="utf-8")
    return "merged" if merge else "written"

