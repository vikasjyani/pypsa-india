def _type_name(annotation) -> str:
    text = str(annotation).replace("typing.", "").replace("<class '", "").replace("'>", "")
    return text.replace("ClassVar[", "").rstrip("]") if "ClassVar" in text else text


def catalogue() -> str:
    """The commented block, built from the dataclasses."""
    lines = [
        BEGIN,
        "#",
        "# Available constraints. Uncomment an entry, give it a",
        "# unique `name`, and it is applied. Numeric fields may be written as a",
        "# year-keyed map covering every modelled year and are resolved per horizon;",
        "# a bare number means the same value in every year.",
        "#",
        "# `scope` narrows a constraint that supports it and is optional there:",
        "# {bus: NR}, {state_id: KL} or {region_id: SR}. Omitted, the constraint",
        "# covers the whole model. ImportExportLimit uses its endpoints instead.",
        "#",
    ]
    for class_name, cls in sorted(C._CONSTRAINT_CLASSES.items()):
        lines.append(f"# {class_name}")
        lines.append(f"#   {PURPOSE.get(class_name, '')}")
        for note in NOTES.get(class_name, ()):
            lines.append(f"#   {note}".rstrip())
        lines.append("#")
        lines.append("#   - class: " + class_name)
        lines.append(f"#     name: my_{class_name.lower()}")
        for field in dataclasses.fields(cls):
            if field.name in COMMON:
                continue
            required = (
                field.default is dataclasses.MISSING
                and field.default_factory is dataclasses.MISSING  # type: ignore[misc]
            )
            if f"{class_name}.{field.name}" in EXAMPLE:
                value = EXAMPLE[f"{class_name}.{field.name}"]
            elif field.name in EXAMPLE:
                value = EXAMPLE[field.name]
            elif field.default is not dataclasses.MISSING and field.default is not None:
                value = repr(field.default)
            else:
                value = f"<{_type_name(field.type)}>"
            # the example may already carry its own trailing comment
            tag = "" if required or "#" in str(value) else "   # optional"
            lines.append(f"#     {field.name}: {value}{tag}")
        lines.append("#")
    lines.append(END)
    return "\n".join(lines)


def apply(path: Path) -> str:
    settings = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(settings, Mapping):
        raise ValueError(f"{path} must contain a YAML mapping.")
    path.write_text(scenario_text(settings), encoding="utf-8")
    return "refreshed"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scenario")
    parser.add_argument("--all", action="store_true")
    args = parser.parse_args()

    targets = available_scenarios() if args.all else [args.scenario]
    if not targets or targets == [None]:
        parser.error("pass --scenario NAME or --all")

    for scenario in targets:
        path = scenario_dir(scenario) / SCENARIO_CONFIG_NAME
        if not path.exists():
            print(f"  {scenario}: no {SCENARIO_CONFIG_NAME}, skipped")
            continue
        print(f"  {scenario}: catalogue {apply(path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
