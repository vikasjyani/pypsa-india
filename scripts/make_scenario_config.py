"""Write scenario-local settings and a commented constraint catalogue.

The catalogue is generated from the constraint dataclasses so it reflects the
available constraint classes and fields.

    python scripts/make_scenario_config.py --all
    python scripts/make_scenario_config.py --scenario er

``write_scenario_config`` is used by the template workflow.  The command-line
interface only refreshes the catalogue block, leaving active settings alone.
"""

